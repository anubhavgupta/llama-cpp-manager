#!/usr/bin/env node
// Human views (.md) for the reconciled SPEC pack (plan.md §2 Phase 3: "JSON canonical + a .md human
// view each"). Generated from the pack JSON by tools/parity/spec-pack.js — never edited by hand.

'use strict';

const fs = require('fs');
const path = require('path');
const C = require('./spec-common');

const cell = (value) => {
    if (value === null || value === undefined) return '—';
    if (Array.isArray(value)) return value.length ? value.map(cell).join(', ') : '—';
    if (typeof value === 'object') return JSON.stringify(value);
    return String(value).replace(/\|/g, '\\|').replace(/\s+/g, ' ').slice(0, 150);
};

const valueOf = (entry) => (entry && typeof entry === 'object' && 'value' in entry ? entry.value : entry);
const sourcesOf = (entry) => (entry && Array.isArray(entry.sources) ? entry.sources.join('+') || '—' : '—');

const table = (headers, rows) => [
    `| ${headers.join(' | ')} |`,
    `|${headers.map(() => '---').join('|')}|`,
    ...rows.map((row) => `| ${row.map(cell).join(' | ')} |`),
    '',
];

const header = (title, artifact) => [
    `# ${title}`,
    '',
    `Human view of \`SPEC/${artifact}.json\`, generated by \`node tools/parity/spec-reconcile.js\`.`,
    'Derivation keys: `a` static read of `parity-baseline`, `b` `fixtures/**` recordings, `c` the',
    'independent model pass. Anything that is not a plain agreement carries a `resolution`; the full',
    'matrix is in `SPEC/CONSISTENCY.md`.',
    '',
];

const notAgree = new Set(['runtime-wins', 'static-over-model', 'static-wording', 'definitional-split', 'agree+runtime-extended', 'complement-from-a', 'complement-from-c', 'a-only', 'c-only', 'runtime-only', 'runtime-note']);

function fieldManifest(pack) {
    const lines = header('Field manifest — the 41 UI fields', 'field-manifest');
    lines.push(`Fields: **${pack.fieldCount}**. Persisted: **${pack.persistedFieldCount}** — ${pack.persistedIntoConfigs.count} into`,
        `\`llamaCppConfigs\` (${pack.persistedIntoConfigs.fields.join(', ')}) and ${pack.persistedIntoSettings.count} into \`llamaCppSettings\``,
        `(${pack.persistedIntoSettings.fields.join(', ')}). The storage-schema pack counts the config set as the persisted field set.`, '');
    lines.push(...table(
        ['#', 'id', 'control', 'persisted', 'CLI flags', 'ini keys', 'default', 'reset on delete', 'derivations'],
        pack.fields.map((field) => {
            const attribute = (name) => field.attributes[name] || {};
            return [
                valueOf(attribute('order')),
                `\`${field.id}\``,
                `${valueOf(attribute('tag'))}${valueOf(attribute('htmlType')) ? `/${valueOf(attribute('htmlType'))}` : ''}`,
                valueOf(attribute('persisted')),
                valueOf(attribute('cliFlags')),
                valueOf(attribute('iniKeys')),
                valueOf(attribute('defaultValue')),
                valueOf(attribute('resetOnDelete')),
                field.gate ? field.gate.derivations.join('+') : '—',
            ];
        }),
    ));
    lines.push('## Rows that are not a plain agreement', '');
    for (const field of pack.fields) {
        for (const [attribute, entry] of Object.entries(field.attributes)) {
            if (!notAgree.has(entry.resolution)) continue;
            const detail = [
                entry.overrides ? `overrides ${entry.overrides.join('/')}` : '',
                entry.rule || '',
                entry.resolutionReason && entry.resolutionReason.length < 90 ? entry.resolutionReason : '',
                entry.modelValue !== undefined ? `model stated ${cell(entry.modelValue)}` : '',
                entry.modelWording !== undefined ? `model phrasing: ${cell(entry.modelWording)}` : '',
                entry.runtimeValue !== undefined ? `runtime ${cell(entry.runtimeValue)}` : '',
            ].filter(Boolean).join(' — ');
            lines.push(`- \`${field.id}.${attribute}\` → ${cell(entry.value)} (\`${entry.resolution}\`)${detail ? ` — ${detail}` : ''}`);
        }
    }
    lines.push('', '## Delete-reset recording', '');
    const reset = pack.deleteResetRecording;
    lines.push(`\`${reset.fixture}\` compared ${reset.controlsCompared} controls across a delete of \`${reset.deletedConfig}\`; only ${cell(reset.changedIds)} moved. The pack uses that recording to settle \`resetOnDelete\` facts.`);
    lines.push('');
    return lines.join('\n');
}

function argTruthTable(pack) {
    const lines = header('Arg truth table — how the argv vector is built', 'arg-truth-table');
    lines.push(cell(pack.emission.orderSemantics.value), '');
    lines.push(`Always appended: ${cell(pack.emission.alwaysAppended.value)} (derivations ${sourcesOf(pack.emission.alwaysAppended)}). Recorded client-built bodies: ${pack.recordedBodies.launches.length}.`, '');
    const ordered = pack.flags.slice().sort((x, y) => (valueOf(x.order) || 0) - (valueOf(y.order) || 0));
    lines.push(...table(['#', 'flag', 'arity', 'value from', 'guard', 'value / recordings'], ordered.map((flag) => [
        valueOf(flag.order), `\`${flag.flag}\``, valueOf(flag.arity), valueOf(flag.fields), valueOf(flag.guard),
        flag.value && /recorded values/.test(String(flag.value.note || '')) ? String(flag.value.note) : cell(valueOf(flag.value)),
    ])));
    lines.push('## Where the recordings are silent', '');
    for (const gap of pack.gaps) lines.push(`- ${gap.__gap ? gap.reason : cell(gap)}`);
    lines.push('');
    return lines.join('\n');
}

function iniMap(pack) {
    const lines = header('ini map — `models-preset.ini` generation', 'ini-map');
    lines.push(`- version header: ${cell(valueOf(pack.structure.versionHeader))}`);
    lines.push(`- line format: ${cell(valueOf(pack.structure.lineFormat))}`);
    lines.push(`- section order: ${cell(valueOf(pack.structure.sectionOrder))}`);
    lines.push(`- trailing line after the last section: ${cell(valueOf(pack.structure.trailingLine))} — ${pack.trailingQuirk.fact}`);
    lines.push(`- name divergences: ${cell(valueOf(pack.structure.nameDivergences))}`, '');
    const ordered = pack.keys.slice().sort((x, y) => (valueOf(x.order) || 0) - (valueOf(y.order) || 0));
    lines.push(...table(['#', 'ini key', 'value from', 'guard', 'CLI counterpart', 'value / recordings'], ordered.map((key) => [
        valueOf(key.order), `\`${key.key}\``, valueOf(key.fields), valueOf(key.guard), cell(valueOf(key.cliCounterpart)),
        key.value && /recorded values/.test(String(key.value.note || '')) ? String(key.value.note) : cell(valueOf(key.value)),
    ])));
    lines.push(`- flags with no ini key: ${cell(pack.cliOnlyFlags)}`);
    lines.push(`- fields never emitted to the ini: ${cell(pack.notEmittedToIni)}`, '');
    lines.push('## Where the recordings are silent', '');
    for (const gap of pack.gaps) lines.push(`- ${gap.__gap ? gap.reason : cell(gap)}`);
    lines.push('');
    return lines.join('\n');
}

function apiContract(doc) {
    const lines = [
        '# API contract — human view',
        '',
        '`SPEC/api-contract.openapi.json` is the machine form (OpenAPI 3.0.3, structure-checked by the',
        'reconciler). This view lists the same routes with their evidence pointers.',
        '',
        `Base URL: \`${doc.servers[0].url}\` — ${doc.servers[0].description}`,
        '',
        ...table(['route', 'statuses', 'status source', 'request body fields', 'evidence'], Object.entries(doc.paths).flatMap(([route, item]) => Object.entries(item).map(([method, operation]) => {
            const body = operation.requestBody && operation.requestBody.content ? Object.values(operation.requestBody.content)[0].schema : null;
            return [
                `\`${method.toUpperCase()} ${route}\``,
                Object.keys(operation.responses).join(', '),
                [...new Set(Object.values(operation.responses).map((response) => response['x-status-source']))].join(' + '),
                body && body.properties ? Object.keys(body.properties).join(', ') : '—',
                (operation['x-evidence'] || []).slice(0, 2).join(', ') || '—',
            ];
        }))),
        '## Server facts',
        '',
        `- listen port: ${cell(valueOf(doc['x-server'].listenPort))} (${sourcesOf(doc['x-server'].listenPort)}) — \`settings.serverPort\` never changes it (Q11)`,
        `- default port constant: ${cell(valueOf(doc['x-server'].defaultPortConstant))}`,
        `- middleware in registration order: ${cell(valueOf(doc['x-server'].middleware))}`,
        `- not app routes: ${cell(doc['x-non-routes'])}`,
        '',
        '## Runtime-only observations',
        '',
        `- restart settle: ${cell(doc['x-runtime-only-observations'].restartEffect.settleNote)}`,
        `- metrics degradation: ${cell(doc['x-runtime-only-observations'].metricsDegradation.note)}`,
        `- client polling: ${cell(doc['x-runtime-only-observations'].clientPolling.counts)} per ${cell(doc['x-runtime-only-observations'].clientPolling.windowMs)} ms window`,
        `- launch-presets port source: ${cell(doc['x-runtime-only-observations'].launchPresetsPortSource && doc['x-runtime-only-observations'].launchPresetsPortSource.settingsJsonServerPort)}`,
        '',
        '## Where the recordings are silent',
        '',
        ...doc['x-status-gaps'].map((gap) => `- ${gap.__gap ? gap.reason : cell(gap)}`),
        '',
    ];
    return lines.join('\n');
}

const factsTable = (facts) => table(['fact', 'value', 'derivations', 'resolution'], Object.entries(facts).map(([fact, entry]) => [
    `\`${fact}\``, cell(entry.value), sourcesOf(entry), entry.resolution,
]));

function socketContract(pack) {
    const lines = header('Socket contract — log streaming', 'socket-contract');
    lines.push(...factsTable(Object.fromEntries(pack.events.map((event) => [event.event, {
        value: { emitted: valueOf(event.emitted), payloadKeys: valueOf(event.payloadKeys) },
        sources: [...new Set([...(event.emitted && event.emitted.sources ? event.emitted.sources : []), ...(event.payloadKeys && event.payloadKeys.sources ? event.payloadKeys.sources : [])])],
        resolution: event.emitted ? event.emitted.resolution : 'agree',
    }]))));
    lines.push(`- events never emitted (recorded fact): ${cell(valueOf(pack.absentEvents))}`);
    lines.push(`- client handlers: ${cell(valueOf(pack.transport.clientHandlers))}`);
    lines.push(`- recorded chunk byte sizes: ${cell(pack.logStreamChunks.value && pack.logStreamChunks.value.chunkByteSizes)}`);
    lines.push(`- recorded connections: ${(pack.recordedConnections || []).length}; event names ${cell([...new Set((pack.recordedConnections || []).flatMap((c) => c.eventNames))].sort())}`);
    lines.push(`- pane rules from the model pass: ${cell(pack.modelPaneRules)}`, '');
    lines.push('## Where the recordings are silent', '');
    for (const gap of pack.gaps) lines.push(`- ${gap.__gap ? gap.reason : cell(gap)}`);
    lines.push('');
    return lines.join('\n');
}

function processLifecycle(pack) {
    const lines = header('Process lifecycle — spawn, kill, exit codes, races', 'process-lifecycle');
    lines.push(...factsTable(pack.facts));
    lines.push('## Races that are requirements', '');
    lines.push(`- Q23: ${cell(pack.raceSemantics && pack.raceSemantics.fact)}`);
    lines.push(`- Q24: ${cell(pack.restartEffect && pack.restartEffect.settleNote)}`);
    lines.push(`- recorded child launches: ${pack.recordedSpawns.count} across ${Object.keys(pack.recordedSpawns.journeys).length} journeys`);
    lines.push(`- exit codes: ${cell(pack.exitCodeEvidence && pack.exitCodeEvidence.note)}`, '');
    lines.push('## Where the recordings are silent', '');
    for (const gap of pack.gaps) lines.push(`- ${gap.__gap ? gap.reason : cell(gap)}`);
    lines.push('');
    return lines.join('\n');
}

function storageSchema(pack) {
    const lines = header('Storage schema — localStorage contract', 'storage-schema');
    lines.push(...factsTable(pack.facts));
    lines.push('## Recorded shapes', '');
    lines.push(`- write order observed: ${cell([...new Set((pack.writeOrder || []).map((w) => (w.order || []).join(' > ')))])}`);
    lines.push(`- settings keys: ${cell(pack.settingsShape.keys)}; port-shaped keys inside configs: ${cell(pack.serverPortInConfigs.observed)}`);
    lines.push(`- config keys seen in the dumps: ${Object.keys(pack.configsShape || {}).length} — the corpus seeds carry keys the save path never writes, and the next save drops them (Q16)`);
    lines.push(`- delete-reset: only ${cell(pack.deleteReset && pack.deleteReset.changedIds)} moved of ${cell(pack.deleteReset && pack.deleteReset.controlsCompared)} compared`);
    lines.push(`- insertion order matters for ini section order: ${cell(pack.facts['@insertionOrder significance'] && pack.facts['@insertionOrder significance'].value)}`, '');
    lines.push('## Where the recordings are silent', '');
    for (const gap of pack.gaps) lines.push(`- ${gap.__gap ? gap.reason : cell(gap)}`);
    lines.push('');
    return lines.join('\n');
}

function writeViews(packOutputs) {
    const views = {
        'field-manifest.md': fieldManifest(packOutputs['field-manifest.json']),
        'arg-truth-table.md': argTruthTable(packOutputs['arg-truth-table.json']),
        'ini-map.md': iniMap(packOutputs['ini-map.json']),
        'api-contract.md': apiContract(packOutputs['api-contract.openapi.json']),
        'socket-contract.md': socketContract(packOutputs['socket-contract.json']),
        'process-lifecycle.md': processLifecycle(packOutputs['process-lifecycle.json']),
        'storage-schema.md': storageSchema(packOutputs['storage-schema.json']),
    };
    for (const [name, text] of Object.entries(views)) fs.writeFileSync(path.join(C.SPEC, name), text);
    return Object.keys(views);
}

module.exports = { writeViews, fieldManifest, argTruthTable, iniMap, apiContract, socketContract, processLifecycle, storageSchema };
